import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";

const testId = randomUUID();
const containerName = `mikage-cache-snapshot-test-${testId.slice(0, 8)}`;
const labelName = "mikage.cache-snapshot-test";
const image = process.env.CACHE_SNAPSHOT_TEST_IMAGE ?? "postgres:17-alpine";
const completedTests = [];
let hasCreatedContainer = false;

function runDocker(argumentsList, input = "") {
  return new Promise((resolve, reject) => {
    const process = spawn("docker", argumentsList, { stdio: ["pipe", "pipe", "pipe"] });
    let output = "";
    let errorOutput = "";
    process.stdout.on("data", chunk => { output += chunk; });
    process.stderr.on("data", chunk => { errorOutput += chunk; });
    process.once("error", reject);
    process.once("exit", code => code === 0 ? resolve(output.trim()) : reject(new Error(`隔離DBの検証に失敗しました (${code}): ${errorOutput.trim()}`)));
    process.stdin.end(input);
  });
}

function runSql(sql) {
  return runDocker(["exec", "-i", containerName, "psql", "-X", "-v", "ON_ERROR_STOP=1", "-qAt", "-U", "postgres", "-d", "snapshot_test"], sql);
}

function readToken() {
  return runSql("SET ROLE anon; SELECT mikage.get_page_cache_revision();");
}

async function waitForReady() {
  for (let attempt = 0; attempt < 80; attempt++) {
    try {
      await runDocker(["exec", containerName, "pg_isready", "-h", "127.0.0.1", "-U", "postgres", "-d", "snapshot_test"]);
      return;
    } catch { await new Promise(resolve => setTimeout(resolve, 250)); }
  }
  throw new Error("隔離PostgreSQLの起動を確認できませんでした。");
}

function openTransaction(initialSql) {
  const process = spawn("docker", ["exec", "-i", containerName, "psql", "-X", "-v", "ON_ERROR_STOP=1", "-qAt", "-U", "postgres", "-d", "snapshot_test"], { stdio: ["pipe", "pipe", "pipe"] });
  let output = "";
  let errorOutput = "";
  let readyResolve;
  let readyReject;
  const ready = new Promise((resolve, reject) => { readyResolve = resolve; readyReject = reject; });
  const completed = new Promise((resolve, reject) => {
    process.stdout.on("data", chunk => {
      output += chunk;
      if (output.includes("transaction-ready")) readyResolve();
    });
    process.stderr.on("data", chunk => { errorOutput += chunk; });
    process.once("error", error => { readyReject(error); reject(error); });
    process.once("exit", code => {
      if (code === 0) resolve(output);
      else {
        const error = new Error(`同時transactionの検証に失敗しました: ${errorOutput.trim()}`);
        readyReject(error);
        reject(error);
      }
    });
  });
  void completed.catch(() => {});
  process.stdin.write(`${initialSql}\nSELECT 'transaction-ready';\n`);
  return { ready, completed, commit() { process.stdin.end("COMMIT;\n"); }, rollback() { if (!process.stdin.writableEnded) process.stdin.end("ROLLBACK;\n"); } };
}

async function expectInvalid(sql, restoreSql, description) {
  // DDLをcommitしてから別要求で確認し、own-XIDガードだけで通る偽陽性を避ける。
  await runSql(sql);
  try { assert.equal(await readToken(), ""); }
  finally { await runSql(restoreSql); }
  assert.match(await readToken(), /^snapshot:[0-9a-f]{64}$/);
  completedTests.push(description);
}

try {
  await runDocker(["run", "--detach", "--name", containerName, "--label", `${labelName}=${testId}`, "--network", "none", "--tmpfs", "/var/lib/postgresql/data", "--env", "POSTGRES_HOST_AUTH_METHOD=trust", "--env", "POSTGRES_DB=snapshot_test", image]);
  hasCreatedContainer = true;
  await waitForReady();
  await runSql(`
    CREATE ROLE anon NOLOGIN;
    CREATE ROLE authenticated NOLOGIN;
    CREATE ROLE other_reader NOLOGIN;
    CREATE SCHEMA mikage;
    CREATE TABLE mikage.targets (key text PRIMARY KEY, name text NOT NULL);
    CREATE TABLE mikage.logs (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, target_key text REFERENCES mikage.targets(key) ON DELETE CASCADE, created_at timestamptz NOT NULL DEFAULT now(), response_time integer);
    CREATE TABLE mikage.incidents (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, keyword text NOT NULL);
    CREATE TABLE public.unrelated (id integer PRIMARY KEY, value text NOT NULL);
    GRANT USAGE ON SCHEMA mikage TO anon, authenticated, other_reader;
    GRANT SELECT ON ALL TABLES IN SCHEMA mikage TO anon, authenticated;
    GRANT INSERT ON mikage.targets TO anon;
    CREATE FUNCTION mikage.get_error_logs(integer, integer) RETURNS jsonb LANGUAGE sql STABLE AS $$
      SELECT jsonb_build_object('logs', COALESCE(jsonb_agg(to_jsonb(logs)), '[]'::jsonb)) FROM mikage.logs
    $$;
    CREATE FUNCTION mikage.get_logs_in_range(text[], timestamptz, timestamptz) RETURNS jsonb LANGUAGE plpgsql STABLE AS $$
      DECLARE result jsonb;
      BEGIN SELECT COALESCE(jsonb_agg(to_jsonb(logs)), '[]'::jsonb) INTO result FROM mikage.logs; RETURN result; END;
    $$;
  `);
  const businessStateSql = `SELECT jsonb_agg(jsonb_build_object('oid',oid,'acl',relacl,'rls',relrowsecurity,'forceRls',relforcerowsecurity) ORDER BY oid)::text FROM pg_class WHERE oid IN ('mikage.targets'::regclass,'mikage.logs'::regclass,'mikage.incidents'::regclass);`;
  const beforeBusinessState = await runSql(businessStateSql);
  const migration = await readFile(new URL("./sql/page-cache-snapshot.sql", import.meta.url), "utf8");
  await runSql(migration);
  assert.equal(await runSql(businessStateSql), beforeBusinessState);
  assert.equal(await runSql("SELECT count(*) FROM pg_trigger WHERE NOT tgisinternal AND tgrelid IN ('mikage.targets'::regclass,'mikage.logs'::regclass,'mikage.incidents'::regclass);"), "0");
  assert.equal(await runSql("SELECT count(*) FROM information_schema.tables WHERE table_schema='mikage';"), "3");
  completedTests.push("業務テーブルの権限・RLS・トリガーを変更せず追跡テーブルも作らない");

  const initialToken = await readToken();
  assert.match(initialToken, /^snapshot:[0-9a-f]{64}$/);
  for (let attempt = 0; attempt < 5; attempt++) assert.equal(await readToken(), initialToken);
  completedTests.push("metadataの連続SELECTだけではsnapshot tokenを変更しない");

  const expectedTokenSql = (monthSql) => `'snapshot:' || encode(sha256(convert_to(jsonb_build_array(current_database(), EXTRACT(EPOCH FROM pg_postmaster_start_time()), pg_current_snapshot()::text, ${monthSql}, current_setting('TimeZone'), current_setting('DateStyle'), current_setting('IntervalStyle'), current_setting('extra_float_digits'))::text, 'UTF8')), 'hex')`;
  const currentMonthSql = "to_char(date_trunc('month', CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Tokyo'), 'YYYY-MM')";
  await runSql(`SET ROLE anon; SELECT 1 / CASE WHEN mikage.get_page_cache_revision() = ${expectedTokenSql(currentMonthSql)} AND mikage.get_page_cache_revision() <> ${expectedTokenSql("to_char(date_trunc('month', CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Tokyo') + interval '1 month', 'YYYY-MM')")} THEN 1 ELSE 0 END;`);
  completedTests.push("tokenにDB名・起動時刻・完全snapshot・現在のJST月・出力設定を含めSHA256化する");

  await runSql(`SELECT 1 / CASE WHEN to_char(date_trunc('month', '2026-10-31 14:59:59+00'::timestamptz AT TIME ZONE 'Asia/Tokyo'), 'YYYY-MM') = '2026-10' AND to_char(date_trunc('month', '2026-10-31 15:00:00+00'::timestamptz AT TIME ZONE 'Asia/Tokyo'), 'YYYY-MM') = '2026-11' THEN 1 ELSE 0 END;`);
  completedTests.push("JSTの月境界はUTC月末15時に切り替わる");

  const readConfiguredToken = async (settings) => JSON.parse(await runSql(`SET ROLE anon; SET TimeZone = '${settings[0]}'; SET DateStyle = '${settings[1]}'; SET IntervalStyle = '${settings[2]}'; SET extra_float_digits = ${settings[3]}; SELECT jsonb_build_object('token', mikage.get_page_cache_revision(), 'snapshot', pg_current_snapshot()::text);`));
  const baseSettings = ["UTC", "ISO, MDY", "postgres", "1"];
  const baseConfiguredToken = await readConfiguredToken(baseSettings);
  for (const [index, name, value] of [[0, "TimeZone", "Asia/Tokyo"], [1, "DateStyle", "SQL, DMY"], [2, "IntervalStyle", "iso_8601"], [3, "extra_float_digits", "3"]]) {
    const settings = [...baseSettings];
    settings[index] = value;
    const changed = await readConfiguredToken(settings);
    assert.equal(changed.snapshot, baseConfiguredToken.snapshot);
    assert.notEqual(changed.token, baseConfiguredToken.token);
    assert.deepEqual(await readConfiguredToken(settings), changed);
    completedTests.push(`DB snapshotが同じでも${name}が違えばtokenを分け、同設定の再読取では安定する`);
  }

  const beforeReadOnlyCalls = await readToken();
  await runSql(`BEGIN; SET LOCAL ROLE anon; SELECT set_config('request.jwt.claims', '{"role":"anon"}', true); SELECT mikage.get_error_logs(0,-1); SELECT mikage.get_logs_in_range(ARRAY[]::text[], now()-interval '1 hour',now()); SELECT 1 / CASE WHEN pg_current_xact_id_if_assigned() IS NULL THEN 1 ELSE 0 END; COMMIT;`);
  assert.equal(await readToken(), beforeReadOnlyCalls);
  completedTests.push("典型的なPostgREST設定とSTABLEのSQL/PLpgSQL読取RPCもXIDを割当てず自己失効しない");

  const mutations = [
    ["targets INSERT", "INSERT INTO mikage.targets VALUES ('example-a','Example A'),('example-b','Example B')"],
    ["targets UPDATE", "UPDATE mikage.targets SET name='Updated' WHERE key='example-b'"],
    ["logs INSERT", "INSERT INTO mikage.logs(target_key,response_time) VALUES ('example-a',1000)"],
    ["logs UPDATE", "UPDATE mikage.logs SET response_time=2000"],
    ["logs DELETE", "DELETE FROM mikage.logs"],
    ["logs TRUNCATE", "TRUNCATE mikage.logs"],
    ["incidents INSERT", "INSERT INTO mikage.incidents(keyword) VALUES ('example')"],
    ["incidents UPDATE", "UPDATE mikage.incidents SET keyword='updated'"],
    ["incidents DELETE", "DELETE FROM mikage.incidents"],
    ["incidents TRUNCATE", "TRUNCATE mikage.incidents"],
    ["targets DELETE", "DELETE FROM mikage.targets WHERE key='example-b'"],
    ["targets TRUNCATE", "TRUNCATE mikage.targets CASCADE"],
  ];
  for (const [label, sql] of mutations) {
    const beforeMutation = await readToken();
    await runSql(`${sql};`);
    assert.notEqual(await readToken(), beforeMutation);
    completedTests.push(`${label}のcommitでtokenを変更する`);
  }

  const beforeRollbackCount = await runSql("SELECT count(*) FROM mikage.targets;");
  await runSql("BEGIN; INSERT INTO mikage.targets VALUES ('rollback','Example'); ROLLBACK;");
  assert.equal(await runSql("SELECT count(*) FROM mikage.targets;"), beforeRollbackCount);
  assert.equal(await runSql("SELECT count(*) FROM mikage.targets WHERE key='rollback';"), "0");
  assert.match(await readToken(), /^snapshot:[0-9a-f]{64}$/);
  completedTests.push("rollback後のデータは元のまま、保守的なtoken失効は許容する");

  const beforeUnrelated = await readToken();
  await runSql("INSERT INTO public.unrelated VALUES(1,'unknown-rpc-dependency');");
  assert.notEqual(await readToken(), beforeUnrelated);
  completedTests.push("未知RPCの依存先を含む無関係な表の書込も保守的に失効する");

  await runSql(migration);
  assert.match(await readToken(), /^snapshot:[0-9a-f]{64}$/);
  assert.equal(await runSql("SELECT count(*) FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='mikage' AND p.proname='get_page_cache_revision';"), "1");
  assert.equal(await runSql(businessStateSql), beforeBusinessState);
  completedTests.push("再適用してもAPIを重複作成せず業務設定を維持する");

  assert.equal(await runSql("SET ROLE authenticated; SELECT mikage.get_page_cache_revision() IS NULL;"), "t");
  await assert.rejects(runSql("SET ROLE other_reader; SELECT mikage.get_page_cache_revision();"), /permission denied/);
  completedTests.push("匿名以外はキャッシュ不可としPUBLICへの実行権限を付与しない");

  await expectInvalid("REVOKE SELECT ON mikage.logs FROM anon;", "GRANT SELECT ON mikage.logs TO anon;", "SELECT権限剥奪後はNULLでキャッシュを停止する");
  await expectInvalid("ALTER TABLE mikage.logs ENABLE ROW LEVEL SECURITY; CREATE POLICY conditional_read ON mikage.logs FOR SELECT TO anon USING(response_time>0);", "DROP POLICY conditional_read ON mikage.logs; ALTER TABLE mikage.logs DISABLE ROW LEVEL SECURITY;", "条件付きRLSではキャッシュしない");
  await runSql("ALTER TABLE mikage.logs ENABLE ROW LEVEL SECURITY; CREATE POLICY open_read ON mikage.logs FOR SELECT TO anon USING(true);");
  assert.match(await readToken(), /^snapshot:[0-9a-f]{64}$/);
  completedTests.push("無条件permissive RLSではcache tokenを返す");
  await expectInvalid("CREATE POLICY restrictive_read ON mikage.logs AS RESTRICTIVE FOR SELECT TO anon USING(true);", "DROP POLICY restrictive_read ON mikage.logs;", "restrictive policyではキャッシュを停止する");
  await expectInvalid("ALTER POLICY open_read ON mikage.logs USING(response_time>0);", "ALTER POLICY open_read ON mikage.logs USING(true);", "RLSを条件付きへ変えると即座にNULLへ切り替える");
  await expectInvalid("REVOKE EXECUTE ON FUNCTION mikage.get_error_logs(integer,integer) FROM PUBLIC;", "GRANT EXECUTE ON FUNCTION mikage.get_error_logs(integer,integer) TO PUBLIC;", "関連RPCの実行権限剥奪後はキャッシュしない");
  await expectInvalid("ALTER FUNCTION mikage.get_error_logs(integer,integer) VOLATILE;", "ALTER FUNCTION mikage.get_error_logs(integer,integer) STABLE;", "既存RPCがVOLATILEなら本文を推測せずキャッシュを停止する");
  await expectInvalid("CREATE TABLE mikage.logs_child() INHERITS(mikage.logs);", "DROP TABLE mikage.logs_child;", "未対応の継承構成は保守的にキャッシュしない");

  await runSql("BEGIN; INSERT INTO public.unrelated VALUES(2,'own-transaction-write'); SET LOCAL ROLE anon; SELECT 1 / CASE WHEN mikage.get_page_cache_revision() IS NULL THEN 1 ELSE 0 END; RESET ROLE; ROLLBACK;");
  completedTests.push("要求自身が書込済みXIDを持つ場合はtokenを返さない");

  const firstWriter = openTransaction("SET statement_timeout='5s'; BEGIN; INSERT INTO mikage.targets VALUES('writer-a','Example A');");
  try {
    await firstWriter.ready;
    const beforeSecondCommit = await readToken();
    await runSql("SET statement_timeout='5s'; BEGIN; INSERT INTO mikage.targets VALUES('writer-b','Example B'); COMMIT;");
    const afterSecondCommit = await readToken();
    assert.notEqual(afterSecondCommit, beforeSecondCommit);
    assert.equal(await runSql("SET ROLE anon; SELECT string_agg(key,',' ORDER BY key) FROM mikage.targets;"), "writer-b");
    firstWriter.commit();
    await firstWriter.completed;
    assert.notEqual(await readToken(), afterSecondCommit);
    assert.equal(await runSql("SET ROLE anon; SELECT string_agg(key,',' ORDER BY key) FROM mikage.targets;"), "writer-a,writer-b");
  } finally { firstWriter.rollback(); }
  completedTests.push("開始順とcommit順が逆でもactive XIDの消失を検知し、MAX採番の取りこぼしを防ぐ");

  assert.equal(await runSql("SELECT pg_is_in_recovery();"), "f");
  assert.match(migration, /pg_catalog\.pg_is_in_recovery\(\)/);
  assert.equal(await runSql("SELECT count(*) FROM pg_trigger WHERE NOT tgisinternal AND tgrelid IN ('mikage.targets'::regclass,'mikage.logs'::regclass,'mikage.incidents'::regclass);"), "0");
  completedTests.push("primary上でのみ利用し、業務書込へ新しい共有行ロックを追加しない");
  console.log(JSON.stringify({ passed: completedTests.length, tests: completedTests, database: "isolated PostgreSQL", productionDatabaseTouched: false }, null, 2));
} finally {
  if (hasCreatedContainer) {
    const owner = await runDocker(["inspect", "--format", `{{ index .Config.Labels "${labelName}" }}`, containerName]);
    if (owner !== testId || !containerName.startsWith("mikage-cache-snapshot-test-")) throw new Error("隔離コンテナの所有を確認できないため削除しません。");
    await runDocker(["rm", "--force", containerName]);
  }
}
