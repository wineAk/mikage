import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";

const testId = randomUUID();
const containerName = `mikage-cache-revision-test-${testId.slice(0, 8)}`;
const labelName = "mikage.cache-revision-test";
const image = process.env.CACHE_REVISION_TEST_IMAGE ?? "postgres:17-alpine";
const completedTests = [];
let hasCreatedContainer = false;

function runDocker(argumentsList, input = "") {
  return new Promise((resolve, reject) => {
    const process = spawn("docker", argumentsList, { stdio: ["pipe", "pipe", "pipe"] });
    let output = "";
    let errorOutput = "";
    process.stdout.on("data", chunk => { output += chunk; });
    process.stderr.on("data", chunk => { errorOutput += chunk; });
    process.once("error", reject);
    process.once("exit", code => {
      if (code === 0) resolve(output.trim());
      else reject(new Error(`Docker test command failed (${code}): ${errorOutput.trim()}`));
    });
    process.stdin.end(input);
  });
}

function runSql(sql) {
  return runDocker(["exec", "-i", containerName, "psql", "-X", "-v", "ON_ERROR_STOP=1", "-qAt", "-U", "postgres", "-d", "revision_test"], sql);
}

async function readRevision() {
  return runSql("SET ROLE anon; SELECT mikage.get_page_cache_revision();");
}

async function expectInvalid(sql, description) {
  await runSql(`BEGIN; ${sql}; SET LOCAL ROLE anon; SELECT 1 / CASE WHEN mikage.get_page_cache_revision() IS NULL THEN 1 ELSE 0 END; RESET ROLE; ROLLBACK;`);
  assert.ok(await readRevision());
  completedTests.push(description);
}

function openSqlTransaction(initialSql) {
  const process = spawn("docker", ["exec", "-i", containerName, "psql", "-X", "-v", "ON_ERROR_STOP=1", "-qAt", "-U", "postgres", "-d", "revision_test"], { stdio: ["pipe", "pipe", "pipe"] });
  let output = "";
  let errorOutput = "";
  let readyResolve;
  let readyReject;
  const ready = new Promise((resolve, reject) => { readyResolve = resolve; readyReject = reject; });
  const completed = new Promise((resolve, reject) => {
    process.stdout.on("data", chunk => {
      output += chunk;
      if (output.includes("transaction-ready")) readyResolve();
    });
    process.stderr.on("data", chunk => { errorOutput += chunk; });
    process.once("error", error => { readyReject(error); reject(error); });
    process.once("exit", code => {
      if (code === 0) resolve(output);
      else {
        const error = new Error(`隔離DBの同時更新に失敗しました: ${errorOutput.trim()}`);
        readyReject(error);
        reject(error);
      }
    });
  });
  // 途中の検証失敗でコンテナを破棄した場合も、未処理のrejectを残さない。
  void completed.catch(() => {});
  process.stdin.write(`${initialSql}\nSELECT 'transaction-ready';\n`);
  return { ready, completed, commit(sqlBeforeCommit = "") { process.stdin.end(`${sqlBeforeCommit}\nCOMMIT;\n`); }, rollback() { if (!process.stdin.writableEnded) process.stdin.end("ROLLBACK;\n"); } };
}

async function waitForReady() {
  for (let attempt = 0; attempt < 80; attempt++) {
    try {
      await runDocker(["exec", containerName, "pg_isready", "-U", "postgres", "-d", "revision_test"]);
      return;
    } catch { await new Promise(resolve => setTimeout(resolve, 250)); }
  }
  throw new Error("隔離PostgreSQLの起動を確認できませんでした。");
}

try {
  // 既存DB、ホストポート、永続ボリュームを使用しない。
  await runDocker(["run", "--detach", "--name", containerName, "--label", `${labelName}=${testId}`, "--network", "none", "--tmpfs", "/var/lib/postgresql/data", "--env", "POSTGRES_HOST_AUTH_METHOD=trust", "--env", "POSTGRES_DB=revision_test", image]);
  hasCreatedContainer = true;
  await waitForReady();
  await runSql(`
    CREATE ROLE anon NOLOGIN;
    CREATE ROLE authenticated NOLOGIN;
    CREATE SCHEMA mikage;
    CREATE TABLE mikage.targets (key text PRIMARY KEY, name text NOT NULL);
    CREATE TABLE mikage.logs (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, target_key text REFERENCES mikage.targets(key) ON DELETE CASCADE, created_at timestamptz NOT NULL DEFAULT now(), response_time integer);
    CREATE TABLE mikage.incidents (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, keyword text NOT NULL);
    GRANT USAGE ON SCHEMA mikage TO anon, authenticated;
    GRANT SELECT ON ALL TABLES IN SCHEMA mikage TO anon, authenticated;
    GRANT INSERT ON mikage.targets TO anon;
    CREATE FUNCTION mikage.get_error_logs(integer, integer) RETURNS jsonb LANGUAGE sql AS $$SELECT '{}'::jsonb$$;
    CREATE FUNCTION mikage.get_logs_in_range(text[], timestamptz, timestamptz) RETURNS jsonb LANGUAGE sql AS $$SELECT '[]'::jsonb$$;
  `);
  const migration = await readFile(new URL("./page-cache-revision.sql", import.meta.url), "utf8");
  await runSql(migration);
  const initialRevision = await readRevision();
  assert.match(initialRevision, /^[0-9a-f-]{36}:0:[0-9a-f]{32}:[0-9a-f]{32}$/);
  assert.equal(await runSql("SET ROLE authenticated; SELECT mikage.get_page_cache_revision() IS NULL;"), "t");
  completedTests.push("匿名の安全な状態だけ文字列revisionを返し、認証済み利用者はキャッシュしない");

  await runSql(`DO $$
    DECLARE previous_revision bigint;
    BEGIN
      SELECT revision INTO previous_revision FROM mikage.page_cache_revision;
      INSERT INTO mikage.targets VALUES ('example-a', 'Example A'), ('example-b', 'Example B');
      IF (SELECT revision FROM mikage.page_cache_revision) <> previous_revision + 1 THEN RAISE EXCEPTION 'bulk insert must bump once'; END IF;
      previous_revision := previous_revision + 1;
      UPDATE mikage.targets SET name = name || ' updated';
      IF (SELECT revision FROM mikage.page_cache_revision) <> previous_revision + 1 THEN RAISE EXCEPTION 'target update missing'; END IF;
      INSERT INTO mikage.logs(target_key, response_time) VALUES ('example-a', 1), ('example-a', 2);
      SELECT revision INTO previous_revision FROM mikage.page_cache_revision;
      UPDATE mikage.logs SET response_time = 3;
      DELETE FROM mikage.logs WHERE response_time = 3;
      TRUNCATE mikage.logs;
      IF (SELECT revision FROM mikage.page_cache_revision) <> previous_revision + 3 THEN RAISE EXCEPTION 'log mutation missing'; END IF;
      INSERT INTO mikage.incidents(keyword) VALUES ('example');
      SELECT revision INTO previous_revision FROM mikage.page_cache_revision;
      UPDATE mikage.incidents SET keyword = 'updated';
      DELETE FROM mikage.incidents;
      TRUNCATE mikage.incidents;
      IF (SELECT revision FROM mikage.page_cache_revision) <> previous_revision + 3 THEN RAISE EXCEPTION 'incident mutation missing'; END IF;
      SELECT revision INTO previous_revision FROM mikage.page_cache_revision;
      DELETE FROM mikage.targets WHERE key = 'example-b';
      TRUNCATE mikage.targets CASCADE;
      IF (SELECT revision FROM mikage.page_cache_revision) <= previous_revision + 1 THEN RAISE EXCEPTION 'target delete/truncate missing'; END IF;
    END $$;`);
  completedTests.push("3表のINSERT・UPDATE・DELETE・TRUNCATEと複数行のstatement単位更新");

  await runSql(`DO $$
    DECLARE previous_revision bigint;
    BEGIN
      SELECT revision INTO previous_revision FROM mikage.page_cache_revision;
      BEGIN
        INSERT INTO mikage.targets VALUES ('rollback', 'Example');
        RAISE EXCEPTION 'intentional rollback';
      EXCEPTION WHEN raise_exception THEN NULL;
      END;
      IF (SELECT revision FROM mikage.page_cache_revision) <> previous_revision OR EXISTS(SELECT 1 FROM mikage.targets WHERE key = 'rollback') THEN RAISE EXCEPTION 'rollback leaked'; END IF;
    END $$;`);
  completedTests.push("ロールバックではデータとrevisionが同時に元へ戻る");

  const beforeRerun = await readRevision();
  await runSql(migration);
  assert.equal(await readRevision(), beforeRerun);
  assert.equal(await runSql("SELECT count(*) FROM pg_trigger WHERE tgname='page_cache_revision_changed' AND NOT tgisinternal;"), "3");
  completedTests.push("再適用してもepoch・revisionを保持しトリガーを重複作成しない");

  assert.equal(await runSql("SELECT has_table_privilege('anon', 'mikage.targets', 'INSERT');"), "t");
  await runSql("SET ROLE anon; INSERT INTO mikage.targets VALUES ('anon-write', 'Example');");
  await assert.rejects(runSql("SET ROLE anon; UPDATE mikage.page_cache_revision SET revision=0;"), /permission denied/);
  await assert.rejects(runSql("SET ROLE anon; SELECT mikage.bump_page_cache_revision();"), /permission denied/);
  completedTests.push("業務テーブルの既存権限を維持し、メタデータへの直接書込とトリガー直接実行を禁止");

  await runSql("UPDATE mikage.page_cache_revision SET revision=9007199254740992; INSERT INTO mikage.targets VALUES ('precise', 'Example');");
  assert.equal((await readRevision()).split(":")[1], "9007199254740993");
  const epochBeforeOverflow = (await readRevision()).split(":")[0];
  await runSql("UPDATE mikage.page_cache_revision SET revision=9223372036854775807; INSERT INTO mikage.targets VALUES ('overflow', 'Example');");
  const afterOverflow = (await readRevision()).split(":");
  assert.equal(afterOverflow[1], "0");
  assert.notEqual(afterOverflow[0], epochBeforeOverflow);
  completedTests.push("JavaScript精度上限を超えるrevisionとbigint上限時のepoch更新");

  await expectInvalid("REVOKE SELECT ON mikage.logs FROM anon", "SELECT権限剥奪後はキャッシュ利用を停止");
  await expectInvalid("ALTER TABLE mikage.logs ENABLE ROW LEVEL SECURITY; CREATE POLICY conditional_read ON mikage.logs FOR SELECT TO anon USING (response_time > 0)", "条件付きRLSではキャッシュ利用を停止");
  await runSql("ALTER TABLE mikage.logs ENABLE ROW LEVEL SECURITY; CREATE POLICY open_read ON mikage.logs FOR SELECT TO anon USING (true);");
  assert.ok(await readRevision());
  completedTests.push("無条件のpermissive SELECT RLSではrevisionを返す");
  await expectInvalid("CREATE POLICY restricted_read ON mikage.logs AS RESTRICTIVE FOR SELECT TO anon USING (true)", "restrictive RLSがある場合はキャッシュ利用を停止");
  await expectInvalid("ALTER POLICY open_read ON mikage.logs USING (response_time > 0)", "無条件policyを条件付きへ変えるとキャッシュ利用を停止");
  await expectInvalid("ALTER TABLE mikage.logs DISABLE TRIGGER page_cache_revision_changed", "トリガー無効化後はキャッシュ利用を停止");
  await expectInvalid("ALTER TABLE mikage.logs ENABLE TRIGGER page_cache_revision_changed", "通常enabledのみではreplica迂回のためキャッシュ利用を停止");
  await expectInvalid("DROP TRIGGER page_cache_revision_changed ON mikage.logs", "トリガー削除後はキャッシュ利用を停止");
  await expectInvalid("REVOKE EXECUTE ON FUNCTION mikage.get_error_logs(integer, integer) FROM PUBLIC", "既存RPCの実行権限剥奪後はキャッシュ利用を停止");
  await expectInvalid("CREATE OR REPLACE FUNCTION mikage.bump_page_cache_revision() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$BEGIN RETURN NULL; END;$$", "トリガー関数が書き換わった場合もキャッシュ利用を停止");
  await expectInvalid("DELETE FROM mikage.page_cache_revision", "revisionメタデータが失われた場合はキャッシュ利用を停止");
  await expectInvalid("CREATE TABLE mikage.logs_child () INHERITS (mikage.logs)", "子表への直接更新でtriggerを迂回できる継承構成はキャッシュしない");

  await runSql("BEGIN; DROP POLICY open_read ON mikage.logs; CREATE POLICY public_read ON mikage.logs FOR SELECT TO PUBLIC USING (true); SET LOCAL ROLE anon; SELECT 1 / CASE WHEN mikage.get_page_cache_revision() IS NOT NULL THEN 1 ELSE 0 END; RESET ROLE; ROLLBACK;");
  completedTests.push("PUBLIC向けの無条件permissive RLSも安全に評価する");

  const beforeDefinitionChange = await readRevision();
  await runSql("CREATE OR REPLACE FUNCTION mikage.get_error_logs(integer, integer) RETURNS jsonb LANGUAGE sql AS $$SELECT '{\"changed\":true}'::jsonb$$;");
  assert.notEqual(await readRevision(), beforeDefinitionChange);
  completedTests.push("既存RPCのSQL定義が変わるとrevision tokenも変わる");

  const beforeReplicaWrite = await readRevision();
  await runSql("SET session_replication_role=replica; INSERT INTO mikage.targets VALUES ('replica', 'Example'); RESET session_replication_role;");
  assert.notEqual(await readRevision(), beforeReplicaWrite);
  completedTests.push("replicaモードの更新でもALWAYSトリガーが版を更新する");

  const concurrentStart = BigInt((await readRevision()).split(":")[1]);
  const firstWriter = openSqlTransaction("BEGIN; INSERT INTO mikage.targets VALUES ('writer-a', 'Example');");
  try {
    await firstWriter.ready;
    const visibleDuringWrite = BigInt((await readRevision()).split(":")[1]);
    assert.equal(visibleDuringWrite, concurrentStart);
    const secondApplicationName = `revision-writer-${testId}`;
    const secondWriter = runSql(`SET application_name='${secondApplicationName}'; BEGIN; INSERT INTO mikage.targets VALUES ('writer-b', 'Example'); COMMIT;`);
    void secondWriter.catch(() => {});
    let hasObservedRowLock = false;
    for (let attempt = 0; attempt < 40; attempt++) {
      const isWaiting = await runSql(`SELECT EXISTS(SELECT 1 FROM pg_stat_activity WHERE application_name='${secondApplicationName}' AND state='active' AND wait_event_type='Lock');`);
      if (isWaiting === "t") { hasObservedRowLock = true; break; }
      await new Promise(resolve => setTimeout(resolve, 50));
    }
    assert.equal(hasObservedRowLock, true, "2番目の更新が同じrevision rowで待機することを確認します。");
    firstWriter.commit();
    await Promise.all([firstWriter.completed, secondWriter]);
  } finally { firstWriter.rollback(); }
  assert.equal(BigInt((await readRevision()).split(":")[1]), concurrentStart + 2n);
  completedTests.push("未commitの版を見せず、同時更新のcommit後に両方を反映");

  await runSql("INSERT INTO mikage.logs(id, response_time) VALUES (10001, 1); INSERT INTO mikage.incidents(id, keyword) VALUES (10001, 'before-order');");
  const orderedWriter = openSqlTransaction("SET statement_timeout='5s'; BEGIN; UPDATE mikage.logs SET response_time=2 WHERE id=10001;");
  try {
    await orderedWriter.ready;
    const blockedApplicationName = `before-order-writer-${testId}`;
    const blockedWriter = runSql(`SET application_name='${blockedApplicationName}'; SET statement_timeout='5s'; BEGIN; UPDATE mikage.incidents SET keyword='writer-b' WHERE id=10001; COMMIT;`);
    void blockedWriter.catch(() => {});
    let hasObservedRevisionWait = false;
    for (let attempt = 0; attempt < 40; attempt++) {
      const isWaiting = await runSql(`SELECT EXISTS(SELECT 1 FROM pg_stat_activity WHERE application_name='${blockedApplicationName}' AND state='active' AND wait_event_type='Lock');`);
      if (isWaiting === "t") { hasObservedRevisionWait = true; break; }
      await new Promise(resolve => setTimeout(resolve, 50));
    }
    assert.equal(hasObservedRevisionWait, true);
    orderedWriter.commit("UPDATE mikage.incidents SET keyword='writer-a' WHERE id=10001;");
    await Promise.all([orderedWriter.completed, blockedWriter]);
    assert.equal(await runSql("SELECT keyword FROM mikage.incidents WHERE id=10001;"), "writer-b");
  } finally { orderedWriter.rollback(); }
  completedTests.push("BEFORE triggerで版ロックを先に取得し通常DMLの逆順rowlock cycleを避ける");

  console.log(JSON.stringify({ passed: completedTests.length, tests: completedTests, database: "isolated PostgreSQL", productionDatabaseTouched: false }, null, 2));
} finally {
  if (hasCreatedContainer) {
    // この実行が新規作成した専用コンテナだけを、所有ラベル確認後に破棄する。
    const owner = await runDocker(["inspect", "--format", `{{ index .Config.Labels "${labelName}" }}`, containerName]);
    if (owner !== testId || !containerName.startsWith("mikage-cache-revision-test-")) throw new Error("隔離コンテナの所有を確認できないため削除しません。");
    await runDocker(["rm", "--force", containerName]);
  }
}
