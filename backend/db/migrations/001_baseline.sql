CREATE SCHEMA IF NOT EXISTS mikage;
REVOKE ALL ON SCHEMA mikage FROM PUBLIC;

CREATE TABLE mikage.targets (
  key text PRIMARY KEY,
  name text NOT NULL,
  url text NOT NULL,
  headers jsonb,
  is_enabled boolean NOT NULL DEFAULT true
);

CREATE TABLE mikage.logs (
  id integer GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME mikage.logs_id_seq) PRIMARY KEY,
  target_key text NOT NULL REFERENCES mikage.targets (key),
  created_at timestamptz NOT NULL,
  response_time integer,
  status_code integer,
  status_message text,
  error_name text,
  error_code text
);

CREATE INDEX idx_logs_created_at ON mikage.logs USING btree (created_at);
CREATE INDEX idx_logs_target_key ON mikage.logs USING btree (target_key);
CREATE INDEX idx_logs_target_key_created_at ON mikage.logs USING btree (target_key, created_at);
CREATE INDEX idx_logs_error_created_at ON mikage.logs USING btree (created_at)
WHERE (
  status_code IS DISTINCT FROM 200
  OR status_code IS NULL
  OR error_code IS NOT NULL
)
AND error_code IS DISTINCT FROM 'NO_INTERNET';

CREATE TABLE mikage.incidents (
  id bigint GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME mikage.incidents_id_seq) PRIMARY KEY,
  keyword text NOT NULL DEFAULT 'unknown',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  count bigint NOT NULL DEFAULT 1,
  is_closed boolean,
  instatus_id text,
  googlechat_name text
);

CREATE TABLE mikage.watch_scheduler_lock (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  last_reserved_slot timestamptz NOT NULL
);

CREATE TABLE mikage.watch_target_states (
  target_key text PRIMARY KEY REFERENCES mikage.targets (key) ON DELETE CASCADE,
  last_reserved_at timestamptz,
  last_checked_at timestamptz,
  first_failed_at timestamptz,
  failure_confirmed_at timestamptz,
  response_time double precision,
  status_code integer,
  status_message text,
  error_name text,
  error_code text
);

GRANT USAGE ON SCHEMA mikage TO mikage_api;
GRANT SELECT ON mikage.targets TO mikage_api;
