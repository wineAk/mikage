CREATE TABLE mikage.target_change_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME mikage.target_change_audit_id_seq) PRIMARY KEY,
  changed_at timestamptz NOT NULL DEFAULT now(),
  target_key text NOT NULL,
  operation text NOT NULL CHECK (operation IN ('create', 'update', 'enable', 'disable')),
  changed_fields text[] NOT NULL
);

REVOKE ALL ON mikage.target_change_audit FROM PUBLIC;
GRANT SELECT, INSERT, UPDATE ON mikage.targets TO mikage_api;
GRANT INSERT ON mikage.target_change_audit TO mikage_api;
GRANT USAGE, SELECT ON SEQUENCE mikage.target_change_audit_id_seq TO mikage_api;
